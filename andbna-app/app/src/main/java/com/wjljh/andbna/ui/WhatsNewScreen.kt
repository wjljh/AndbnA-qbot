## 新增：群管理

Bot 编辑页「群配置」下面多了一张 `群管理` 卡片，点进去是群列表，再点某个群就是它的规则页。

### 违规自动处理
- 每个群单独一份规则：判定方式（关键词 / 关键词 + 模型复核 / 只用模型）、关键词表（逐行增删）、惩罚阶梯（第几次禁言多少分钟，行数随便加）；
- 命中后按顺序做三件事：**撤回那条消息** → **按次数禁言** → **@ 对方警告**；警告不是写死的文案，而是把「事实 + 第几次 + 处理结果」交给 bot 的人格自己组织语气；
- 到第 N 次（可改，默认 3）尝试**踢出群**；没权限或接口不支持时自动退化为「最长档禁言 + 警告」，原因写进日志，不会反复刷错误；
- 关键词只是初筛，判违规前会把这句连同上下文交给判定模型确认一次——「我挂科了」这类不会被误伤。

### 次数是共享的
- 群号和成员 openid 都是每只 bot 一套，所以计数按「群名 + 昵称」跨 bot 累计：任意一只记到的都算在一起，不会出现「同一人被不同 bot 记成第 1 次、禁言时长判错」；
- 昵称拿不到时退化为该 bot 内独立计，日志会写明。已知限制：同群重名无法区分；
- 多只 bot 在同一个群时，命中后只有一只真正动手，另一只记「已由 X 处理，本 bot 不动」。

### 进群欢迎
- `问候` 卡片里新增一行「进群欢迎」：开开关、`@ 新成员`、欢迎语；
- **内置人格用固定欢迎语、不可修改**（跟定时问候一个规矩：内容归人格、开关归用户）；自定义人格可以自己写；
